import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {retrieve} from '../../../tools/agentic-workbench/retrieval.mjs';
import {runAssistant} from '../../../tools/agentic-workbench/workflow.mjs';
const root=fileURLToPath(new URL('../../../',import.meta.url));
const oldText=execFileSync('git',['show','2bafb8c:tools/agentic-workbench/retrieval.mjs'],{cwd:root,encoding:'utf8'});
const old=await import('data:text/javascript;base64,'+Buffer.from(oldText).toString('base64'));
const base={documentId:'master',path:'DOCUMENT_MAITRE_GYM.md',priority:1,version:'fixture',visibility:'internal',status:'active'};
const conflicting=[{...base,id:'a',excerpt:'Commission reservations : 15 pourcent.'},{...base,id:'b',excerpt:'Commission reservations : 10 pourcent.'}];
assert.equal(old.retrieve(conflicting,'commission reservations').length,2);
assert.equal(retrieve(conflicting,'commission reservations').length,1);
const one=await runAssistant({question:'commission reservations',principal:'admin',load:async()=>conflicting});
assert.equal(one.status,'sources');assert.equal(one.sources.length,1);
const chunks=Array.from({length:8},(_,i)=>({...base,documentId:'d'+i,id:'c'+i,excerpt:i===0?'orchestration':'coach tarif'}));
assert.equal(old.retrieve(chunks,'coach tarif orchestration')[0].hits,2);
assert.equal(retrieve(chunks,'coach tarif orchestration')[0].hits,1);
const two=await runAssistant({question:'coach tarif orchestration',principal:'admin',load:async()=>chunks});
assert.equal(two.status,'abstained');
console.log(JSON.stringify({reviewedCommit:execFileSync('git',['rev-parse','HEAD'],{cwd:root,encoding:'utf8'}).trim(),fixturesOnly:true,contradiction:{oldPassages:2,currentPassages:1,currentStatus:one.status},coverage:{oldTopHits:2,currentTopHits:1,currentStatus:two.status}},null,2));
